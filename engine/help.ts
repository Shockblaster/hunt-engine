export function usage(cmd?: string): Record<string, unknown> {
  if (cmd && USAGE[cmd]) return { command: cmd, usage: USAGE[cmd], note: 'Add --ws <slug> to name the workspace. Help never runs the command.' };
  return {
    usage: 'he <command> [options]   (he <command> --help for one command)',
    commands: Object.keys(USAGE),
    note: 'Every command prints JSON. Add --ws <slug> to name the workspace; without it the current workspace is used.',
    ...(cmd && cmd !== 'help' ? { unknown: cmd } : {}),
  };
}
